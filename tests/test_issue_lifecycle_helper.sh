#!/usr/bin/env bash
# tests/test_issue_lifecycle_helper.sh
# Comprehensive test suite for .agents/scripts/issue_lifecycle_helper.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HELPER="${SCRIPT_DIR}/.agents/scripts/issue_lifecycle_helper.sh"

TMP_DIR="$(mktemp -d /tmp/issue_lifecycle_test_XXXXXX)"
trap 'rm -rf "$TMP_DIR"' EXIT

echo "=== Running issue_lifecycle_helper.sh test suite ==="

# Test 1: --generate-verification-id
echo -n "Test 1: --generate-verification-id format ... "
VER_ID="$("$HELPER" --generate-verification-id 42 10 1)"
if [[ ! "$VER_ID" =~ ^ver-[0-9]{8}-42-pr10-1$ ]]; then
  echo "FAILED: Verification ID '$VER_ID' did not match expected regex"
  exit 1
fi

VER_ID_HASH="$("$HELPER" --generate-verification-id "#42" "#pr10" 2)"
if [[ ! "$VER_ID_HASH" =~ ^ver-[0-9]{8}-42-pr10-2$ ]]; then
  echo "FAILED: Verification ID with hash '$VER_ID_HASH' did not match expected regex"
  exit 1
fi
echo "PASSED"

# Test 2: --resolve-model (explicit flag, env var, normalization)
echo -n "Test 2: --resolve-model multi-tier resolution and normalization ... "
M1="$("$HELPER" --resolve-model --model "claude-3.7-sonnet")"
if [[ "$M1" != "claude-3-7-sonnet" ]]; then
  echo "FAILED: Expected claude-3-7-sonnet, got '$M1'"
  exit 1
fi

M2="$("$HELPER" --resolve-model "gemini-3.8-flash-high")"
if [[ "$M2" != "gemini-3.8-flash-high" ]]; then
  echo "FAILED: Expected gemini-3.8-flash-high, got '$M2'"
  exit 1
fi

M3="$(AI_MODEL="claude-opus-5.5" "$HELPER" --resolve-model)"
if [[ "$M3" != "claude-opus-5-5-high" ]]; then
  echo "FAILED: Expected claude-opus-5-5-high from AI_MODEL, got '$M3'"
  exit 1
fi

M4="$("$HELPER" --resolve-model --model "Gemini_3.8_Flash High")"
if [[ "$M4" != "gemini-3.8-flash-high" ]]; then
  echo "FAILED: Expected normalized gemini-3.8-flash-high, got '$M4'"
  exit 1
fi

M5="$(env -i PATH="$PATH" "$HELPER" --resolve-model --model "")"
if [[ -z "$M5" ]]; then
  echo "FAILED: Expected fallback slug, got empty string"
  exit 1
fi
echo "PASSED"

# Test 3: --format-verification-review with --model and --implementing-model
echo -n "Test 3: --format-verification-review with model provenance ... "
REVIEW_MD="$TMP_DIR/review.md"
"$HELPER" --format-verification-review \
  --verification-id "ver-20261016-42-pr10-1" \
  --issue 42 \
  --pr 10 \
  --commit-sha "a1b2c3d4e5f6" \
  --cycle 1 \
  --verdict "APPROVED" \
  --model "claude-3-7-sonnet" \
  --implementing-model "gemini-3.8-flash-high" \
  --test-results '{"LiteSVM":"PASSED"}' \
  --checklist '[{"criterion":"Pass all invariant tests","status":"SATISFIED"}]' \
  --findings '[]' \
  --output-file "$REVIEW_MD" >/dev/null

if ! grep -q '"model": "claude-3-7-sonnet"' "$REVIEW_MD"; then
  echo "FAILED: 'model' not found in embedded metadata"
  cat "$REVIEW_MD"
  exit 1
fi

if ! grep -q '"implementing_model": "gemini-3.8-flash-high"' "$REVIEW_MD"; then
  echo "FAILED: 'implementing_model' not found in embedded metadata"
  cat "$REVIEW_MD"
  exit 1
fi

if ! grep -q '\*\*Implementing Model:\*\* `gemini-3.8-flash-high`' "$REVIEW_MD"; then
  echo "FAILED: Implementing Model badge missing or malformed in markdown"
  cat "$REVIEW_MD"
  exit 1
fi

if ! grep -q '\*\*Verified by Model:\*\* `claude-3-7-sonnet`' "$REVIEW_MD"; then
  echo "FAILED: Verified by Model badge missing or malformed in markdown"
  cat "$REVIEW_MD"
  exit 1
fi

if ! grep -q '<sub>\*Generated by `/pr-verify` using `claude-3-7-sonnet` against closed issue specification.\*</sub>' "$REVIEW_MD"; then
  echo "FAILED: Footer attribution missing or malformed in markdown"
  cat "$REVIEW_MD"
  exit 1
fi
echo "PASSED"

# Test 4: --parse-verification extracting model and implementing_model
echo -n "Test 4: --parse-verification extracting model provenance ... "
cat << 'EOF' > "$TMP_DIR/mock_pr_payload.json"
{
  "number": 10,
  "title": "feat(core): implement feature (Closes #42)",
  "body": "<!-- ai-issue-implement: {\"version\":\"1.0\",\"issue_number\":42,\"model\":\"gemini-3.8-flash-high\"} -->\nCloses #42.\n\nAI-Model: gemini-3.8-flash-high",
  "author": {"login": "dev-agent"},
  "state": "OPEN",
  "headRefName": "feat/issue-42-reallocation",
  "baseRefName": "dev",
  "commits": [
    {"oid": "a1b2c3d4e5f6", "committedDate": "2026-10-16T12:00:00Z"}
  ],
  "reviews": [
    {
      "author": {"login": "verifier-agent"},
      "submittedAt": "2026-10-16T12:30:00Z",
      "state": "APPROVED",
      "body": "<!-- ai-pr-verification: {\n  \"version\": \"1.0\",\n  \"verification_id\": \"ver-20261016-42-pr10-1\",\n  \"issue_number\": 42,\n  \"pr_number\": 10,\n  \"commit_sha\": \"a1b2c3d4e5f6\",\n  \"cycle\": 1,\n  \"verdict\": \"APPROVED\",\n  \"model\": \"claude-3-7-sonnet\",\n  \"implementing_model\": \"gemini-3.8-flash-high\",\n  \"test_results\": {\"LiteSVM\": \"PASSED\"},\n  \"acceptance_checklist\": [],\n  \"findings\": []\n} -->\n## Approved"
    }
  ],
  "comments": []
}
EOF

PARSE_PR_OUT="$TMP_DIR/parsed_pr.json"
"$HELPER" --parse-verification --file "$TMP_DIR/mock_pr_payload.json" > "$PARSE_PR_OUT"

VER_MODEL="$(jq -r .model "$PARSE_PR_OUT")"
IMPL_MODEL="$(jq -r .implementing_model "$PARSE_PR_OUT")"

if [[ "$VER_MODEL" != "claude-3-7-sonnet" ]]; then
  echo "FAILED: Expected model claude-3-7-sonnet, got '$VER_MODEL'"
  cat "$PARSE_PR_OUT"
  exit 1
fi

if [[ "$IMPL_MODEL" != "gemini-3.8-flash-high" ]]; then
  echo "FAILED: Expected implementing_model gemini-3.8-flash-high, got '$IMPL_MODEL'"
  cat "$PARSE_PR_OUT"
  exit 1
fi
echo "PASSED"

# Test 5: --check-revision-readiness state machine transitions
echo -n "Test 5: --check-revision-readiness state machine transitions ... "
# 5a: No verification
cat << 'EOF' > "$TMP_DIR/mock_unverified.json"
{
  "number": 11,
  "body": "<!-- ai-issue-implement: {\"version\":\"1.0\",\"issue_number\":55,\"model\":\"claude-3-7-sonnet\"} -->",
  "reviews": [],
  "comments": [],
  "commits": []
}
EOF
READINESS_INIT="$("$HELPER" --check-revision-readiness --file "$TMP_DIR/mock_unverified.json")"
S_INIT="$(echo "$READINESS_INIT" | jq -r .status)"
if [[ "$S_INIT" != "READY_FOR_INITIAL_VERIFICATION" ]]; then
  echo "FAILED: Expected READY_FOR_INITIAL_VERIFICATION, got '$S_INIT'"
  exit 1
fi
IMPL_INIT="$(echo "$READINESS_INIT" | jq -r .implementing_model)"
if [[ "$IMPL_INIT" != "claude-3-7-sonnet" ]]; then
  echo "FAILED: Expected implementing_model 'claude-3-7-sonnet' in check-revision-readiness unverified, got '$IMPL_INIT'"
  exit 1
fi

# 5b: Approved
READINESS_APP="$("$HELPER" --check-revision-readiness --file "$TMP_DIR/mock_pr_payload.json")"
S_APP="$(echo "$READINESS_APP" | jq -r .status)"
if [[ "$S_APP" != "ALREADY_APPROVED" ]]; then
  echo "FAILED: Expected ALREADY_APPROVED, got '$S_APP'"
  exit 1
fi
IMPL_APP="$(echo "$READINESS_APP" | jq -r .implementing_model)"
if [[ "$IMPL_APP" != "gemini-3.8-flash-high" ]]; then
  echo "FAILED: Expected implementing_model 'gemini-3.8-flash-high' in check-revision-readiness output, got '$IMPL_APP'"
  exit 1
fi

# 5c: Changes requested without commits ahead
cat << 'EOF' > "$TMP_DIR/mock_cr_awaiting.json"
{
  "number": 12,
  "body": "",
  "commits": [
    {"oid": "c1", "committedDate": "2026-10-16T10:00:00Z"}
  ],
  "reviews": [
    {
      "submittedAt": "2026-10-16T11:00:00Z",
      "body": "<!-- ai-pr-verification: {\"verdict\":\"CHANGES_REQUESTED\",\"cycle\":1} -->"
    }
  ],
  "comments": []
}
EOF
S_AWAIT="$(jq -r .status <("$HELPER" --check-revision-readiness --file "$TMP_DIR/mock_cr_awaiting.json"))"
if [[ "$S_AWAIT" != "AWAITING_REVISION" ]]; then
  echo "FAILED: Expected AWAITING_REVISION, got '$S_AWAIT'"
  exit 1
fi

# 5d: Changes requested with commits ahead
cat << 'EOF' > "$TMP_DIR/mock_cr_ready.json"
{
  "number": 12,
  "body": "",
  "commits": [
    {"oid": "c1", "committedDate": "2026-10-16T10:00:00Z"},
    {"oid": "c2", "committedDate": "2026-10-16T12:00:00Z"}
  ],
  "reviews": [
    {
      "submittedAt": "2026-10-16T11:00:00Z",
      "body": "<!-- ai-pr-verification: {\"verdict\":\"CHANGES_REQUESTED\",\"cycle\":1} -->"
    }
  ],
  "comments": []
}
EOF
S_READY="$(jq -r .status <("$HELPER" --check-revision-readiness --file "$TMP_DIR/mock_cr_ready.json"))"
if [[ "$S_READY" != "READY_FOR_RE_VERIFICATION" ]]; then
  echo "FAILED: Expected READY_FOR_RE_VERIFICATION, got '$S_READY'"
  exit 1
fi

# 5e: Circuit breaker (Cycle 2 changes requested, 0 commits ahead)
cat << 'EOF' > "$TMP_DIR/mock_cb.json"
{
  "number": 12,
  "body": "",
  "commits": [
    {"oid": "c1", "committedDate": "2026-10-16T10:00:00Z"}
  ],
  "reviews": [
    {
      "submittedAt": "2026-10-16T11:00:00Z",
      "body": "<!-- ai-pr-verification: {\"verdict\":\"CHANGES_REQUESTED\",\"cycle\":2} -->"
    }
  ],
  "comments": []
}
EOF
S_CB="$(jq -r .status <("$HELPER" --check-revision-readiness --file "$TMP_DIR/mock_cb.json"))"
if [[ "$S_CB" != "CIRCUIT_BREAKER_TRIPPED" ]]; then
  echo "FAILED: Expected CIRCUIT_BREAKER_TRIPPED, got '$S_CB'"
  exit 1
fi
echo "PASSED"

# Test 6: Native git commit --trailer extraction verification
echo -n "Test 6: Native git commit --trailer extraction ... "
GIT_TEST_DIR="$TMP_DIR/git_repo"
mkdir -p "$GIT_TEST_DIR"
(
  cd "$GIT_TEST_DIR"
  git init -q
  git config user.name "Test Agent"
  git config user.email "agent@example.com"
  git commit -q --allow-empty -m "feat(test): check commit trailers" --trailer "AI-Model: gemini-3.8-flash-high"
)
TRAILER_RAW="$(git -C "$GIT_TEST_DIR" log -1 --format="%(trailers:key=AI-Model)")"
TRAILER_CLEAN="$(echo "$TRAILER_RAW" | tr -d '\r\n')"
if [[ "$TRAILER_CLEAN" != "AI-Model: gemini-3.8-flash-high" ]]; then
  echo "FAILED: Expected 'AI-Model: gemini-3.8-flash-high', got '$TRAILER_CLEAN'"
  exit 1
fi

TRAILER_VAL="$(git -C "$GIT_TEST_DIR" log -1 --format="%(trailers:key=AI-Model,valueonly)" | tr -d '\r\n ')"
if [[ "$TRAILER_VAL" != "gemini-3.8-flash-high" ]]; then
  echo "FAILED: Expected valueonly 'gemini-3.8-flash-high', got '$TRAILER_VAL'"
  exit 1
fi
echo "PASSED"

echo "=== All issue_lifecycle_helper.sh tests passed successfully! ==="
